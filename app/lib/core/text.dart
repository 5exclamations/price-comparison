/// Нормализация азербайджанского текста для поиска.
///
/// Порядок шагов важнее самих замен. Классическая ловушка: `toLowerCase()`
/// первым. В JavaScript и в Postgres `lower('İ')` даёт `'i'` + комбинирующую
/// точку U+0307, и «milka» перестаёт находить «MİLKA».
///
/// В Dart 3.13 `'İ'.toLowerCase()` возвращает голую `'i'` без точки — проверено
/// тестом. Порядок это не отменяет: нормализация обязана совпадать с серверной
/// `qiymet_norm`, а там lower() ведёт себя по-старому. Полагаться на текущую
/// доброту Dart значит поставить поиск в зависимость от версии SDK.
///
/// Отсюда порядок:
///   1. заменить заглавные İ I Ə Ö Ü Ç Ş Ğ на строчную латиницу, а заодно
///      свернуть кириллические двойники А Е О С Р Х У К в обоих регистрах;
///   2. только теперь `toLowerCase()`;
///   3. разложить в NFD и снести диакритику U+0300–U+036F;
///   4. заменить оставшиеся строчные ə ı и прочие;
///   5. свернуть двойники ещё раз — иначе функция не идемпотентна.
///
/// Шаг 3 подчищает и то, что могло прийти уже разложенным: если клавиатура
/// или чужой код прислали 'I' + U+0307 вместо 'İ', результат всё равно 'i'.
///
/// Та же логика живёт на сервере в SQL-функции `qiymet_norm`, и поиск по
/// каталогу выполняет именно она. Здесь нормализация нужна для локальной
/// фильтрации: подсветка совпадений, отбор в кеше, сравнение строк без
/// похода в сеть.
library;

import 'package:unorm_dart/unorm_dart.dart' as unorm;

/// Шаг 1: заглавные, которые обязаны быть заменены ДО `toLowerCase()`.
const Map<String, String> _upperFirst = {
  'İ': 'i',
  'I': 'i',
  'Ə': 'a',
  'Ö': 'o',
  'Ü': 'u',
  'Ç': 'c',
  'Ş': 's',
  'Ğ': 'g',
};

/// Кириллические двойники латиницы: А Е О С Р Х У К и их строчные.
///
/// Сети мешают алфавиты внутри одного названия — «Кока-Кола» приходит с
/// кириллическими К, о, к, а, зато «Coca-Cola» рядом латиницей. Без сворачивания
/// это два разных товара для поиска.
///
/// Таблица дословно повторяет SQL-функцию `qiymet_norm` (миграция 0005) и
/// `pipeline.norm_name`. Расхождение здесь означает, что локальная фильтрация
/// показывает не то, что нашёл сервер: буквы выглядят одинаково, а строки
/// не совпадают. Сторожится тестом «смесь латиницы с кириллицей».
const Map<String, String> _cyrillicLookalikes = {
  'А': 'a',
  'а': 'a',
  'Е': 'e',
  'е': 'e',
  'О': 'o',
  'о': 'o',
  'С': 'c',
  'с': 'c',
  'Р': 'p',
  'р': 'p',
  'Х': 'x',
  'х': 'x',
  'У': 'y',
  'у': 'y',
  'К': 'k',
  'к': 'k',
};

/// Шаг 4: строчные, которые NFD не раскладывает.
///
/// ə (U+0259) и ı (U+0131) — самостоятельные буквы без диакритики, разложить
/// их нельзя, только заменить. Остальные (ö, ü, ç, ş, ğ) шаг 3 уже свёл к
/// латинице, но они оставлены здесь явно: если NFD когда-нибудь подменят,
/// поведение не поедет молча.
const Map<String, String> _lowerRest = {
  'ə': 'a',
  'ı': 'i',
  'ö': 'o',
  'ü': 'u',
  'ç': 'c',
  'ş': 's',
  'ğ': 'g',
};

/// Комбинирующие диакритические знаки: U+0300–U+036F.
///
/// Диапазон записан escape-последовательностями намеренно: живые символы
/// U+0300 и U+036F невидимы в редакторе и прилипают к соседней скобке.
final RegExp _combiningMarks = RegExp(r'[\u0300-\u036F]');

/// Приводит строку к виду, пригодному для поиска и сравнения.
///
/// ```dart
/// normalizeAz('MİLKA');    // 'milka'
/// normalizeAz('ÇUĞUNDUR'); // 'cugundur'
/// ```
String normalizeAz(String input) {
  if (input.isEmpty) return '';

  // 1. Заглавные — строго до понижения регистра. Кириллические двойники
  //    сворачиваются здесь же, обоими регистрами сразу, как в SQL.
  var s = input;
  _upperFirst.forEach((from, to) => s = s.replaceAll(from, to));
  _cyrillicLookalikes.forEach((from, to) => s = s.replaceAll(from, to));

  // 2. Теперь понижать регистр безопасно.
  s = s.toLowerCase();

  // 3. NFD и снятие диакритики: ğ -> g + U+0306 -> g.
  s = unorm.nfd(s).replaceAll(_combiningMarks, '');

  // 4. То, что NFD не разложил.
  _lowerRest.forEach((from, to) => s = s.replaceAll(from, to));

  // 5. Двойники ещё раз — уже по результату шага 3.
  //
  // Без этого функция не идемпотентна: «Ё» на шаге 1 не двойник, на шаге 3 NFD
  // раскладывает её в «е» + U+0308 и оставляет кириллическую «е», а второй
  // проход свернул бы её в латинскую «e». Клиент нормализует запрос у себя,
  // сервер применяет qiymet_norm ещё раз — и «ёж» перестал бы находить «Ёж».
  _cyrillicLookalikes.forEach((from, to) => s = s.replaceAll(from, to));

  return s;
}

/// Схлопывает пробелы и обрезает края. Пригодно для поисковой строки,
/// куда пользователь заведомо натыкает лишнего.
String normalizeAzQuery(String input) =>
    normalizeAz(input).replaceAll(RegExp(r'\s+'), ' ').trim();

/// Штрихкод — 8–14 цифр. Пробелы и дефисы сети иногда вставляют сами.
bool looksLikeBarcode(String query) {
  final digits = query.replaceAll(RegExp(r'[\s-]'), '');
  return digits.length >= 8 &&
      digits.length <= 14 &&
      RegExp(r'^\d+$').hasMatch(digits);
}

/// Содержит ли [haystack] подстроку [needle] с точки зрения азербайджанского
/// поиска. Обе стороны нормализуются одинаково — иначе «MİLKA» не найдёт
/// «milka» и наоборот.
bool containsAz(String haystack, String needle) {
  final n = normalizeAzQuery(needle);
  if (n.isEmpty) return true;
  return normalizeAz(haystack).contains(n);
}
