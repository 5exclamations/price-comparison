#!/usr/bin/env bash
#
# Один прогон сбора целиком. Порядок шагов — весь смысл этого файла.
#
#   1. ensure_price_partitions_ahead(3)
#   2. сбор в SQLite (run.py fast|full)
#   3. перелив SQLite -> Postgres
#   4. refresh_after_crawl(): current_prices, затем deal_honesty
#   5. проверки данных (--source crawl, БЕЗ --allow-stale)
#   6. notify run
#
# Почему именно так:
#
# 1 перед 2, потому что иначе первого числа месяца прогон начнёт сыпать
#   в секцию DEFAULT. Данные не потеряются, но уедут в общую кучу, и увидеть
#   это можно будет только по вьюхе price_partitions_health — то есть если
#   специально пойти и посмотреть.
#
# 3 отдельным шагом, потому что пайплайн пишет в SQLite, а не в Postgres.
#   Без перелива шаги 4-6 работали бы со вчерашними данными и молча
#   рапортовали об успехе.
#
# 4 перед 6, потому что notify читает deal_honesty. Со вчерашней витриной
#   воркер не отличит накрученную скидку от настоящей и отправит ровно то,
#   что обещал не отправлять.
#
# 5 перед 6, а не после: если сбор привёз мусор, лучше не рассылать пуши
#   по мусору. Упавшие проверки прогон не останавливают — они уже записаны
#   в dq_runs, приложение показывает плашку, а уведомления мы всё равно
#   придержим (см. ниже).
#
# Логи — в файл с ротацией, не в stdout контейнера.
# -e: любая необработанная ошибка останавливает скрипт. -E: ловушка ERR из
# lib.sh работает и внутри функций. Без -e упавший шаг шёл дальше, и прогон
# заканчивался успехом на половине сделанного.
set -Eeuo pipefail

MODE="${1:-fast}"
# Путь задаётся снаружи, чтобы скрипт можно было прогнать не только
# в контейнере. По умолчанию — тот, что в образе.
: "${ROOT:=/srv/qiymet}"
: "${LOG_DIR:=$ROOT/logs}"
LOG="$LOG_DIR/crawl-${MODE}.log"
mkdir -p "$LOG_DIR"

SCRIPT_NAME=$(basename "$0")

# shellcheck source=lib.sh
. "$ROOT/deploy/scripts/lib.sh"

exec >> >(rotating_tee "$LOG") 2>&1

started=$(date +%s)
say "=== прогон $MODE начат ==="

# --- 1. секции на три месяца вперёд ------------------------------------------
if ! psql_q "SELECT ensure_price_partitions_ahead(3)"; then
    alert "Не удалось создать секции price_observations. Прогон $MODE остановлен: без секции наблюдения уедут в DEFAULT."
    exit 1
fi
say "секции на 3 месяца вперёд: есть"

# --- 2. сбор ------------------------------------------------------------------
cd "$ROOT/pipeline" || exit 1
if ! timeout 3h python3 run.py "$MODE"; then
    alert "Сбор ($MODE) упал. Витрины и уведомления не трогали, показываем прежние данные."
    exit 1
fi
say "сбор $MODE завершён"

# --- 3. перелив в Postgres ----------------------------------------------------
# --no-refresh: витрины пересобираются следующим шагом, явным вызовом. Иначе
# refresh_after_crawl() отработал бы дважды, а это две пересборки deal_honesty
# на всём каталоге.
cd "$ROOT" || exit 1
if ! timeout 30m python3 db/import_sqlite.py \
        --sqlite "$ROOT/pipeline/state/qiymet.db" --no-refresh; then
    alert "Перелив в Postgres упал ($MODE). В базе остались прежние цены."
    exit 1
fi
say "перелив в Postgres завершён"

# --- 3a. сверка счётчиков ДО пересборки витрин ---------------------------------
# Импорт делает эту сверку сам и на расхождении возвращает единицу, не трогая
# витрины. Здесь она повторена отдельным шагом сознательно: порядок «сверить,
# потом собирать» — это свойство ЦЕПОЧКИ, а не деталь одного скрипта, и он
# должен быть виден тому, кто читает прогон, а не только тому, кто читает
# import_sqlite.py.
#
# Восемь count(*) по таблицам стоят секунды. Пересборка deal_honesty по
# половине каталога стоит того, что уведомления уйдут по несуществующим
# падениям цены: у товара, чья вторая половина не доехала, «пропала» цена
# в другой сети.
if ! python3 db/import_sqlite.py \
        --sqlite "$ROOT/pipeline/state/qiymet.db" --verify; then
    alert "Счётчики строк SQLite и Postgres разошлись после перелива ($MODE). Витрины НЕ пересобирались, показываем прежние данные."
    exit 1
fi
say "счётчики строк сошлись"

# --- 4. витрины ---------------------------------------------------------------
if ! psql_q "SELECT refresh_after_crawl()"; then
    alert "refresh_after_crawl() упал. Уведомления пропущены: без свежей deal_honesty накрутку от настоящей скидки не отличить."
    exit 1
fi
say "витрины пересобраны"

# --- 5. проверки данных -------------------------------------------------------
# --source crawl и БЕЗ --allow-stale. Флаг существует только для CI, где база
# поднимается из дампа в репозитории и заведомо несвежая. Здесь проверка
# возраста — главная: она ловит сеть, переставшую обновляться.
if python3 -m checks.runner --source crawl; then
    say "проверки данных: все прошли"
    checks_ok=1
else
    # Плашку в приложении включит сам факт записи в dq_runs. Здесь остаётся
    # решить, слать ли пуши по данным, которые мы только что назвали плохими.
    alert "Проверки данных упали после прогона $MODE. Приложение показывает плашку «данные обновляются». Уведомления пропущены."
    checks_ok=0
fi

# --- 6. уведомления -----------------------------------------------------------
if [ "$checks_ok" = "1" ]; then
    if ! timeout 15m python3 -m notify run; then
        alert "notify run упал после прогона $MODE. Подписчики не получили пуши."
    else
        say "уведомления разобраны"
    fi
else
    say "уведомления пропущены: проверки данных не прошли"
fi

# Пульс внешнему монитору. Отправляется ТОЛЬКО после полного прохода всех
# шагов: пульс на упавшем прогоне означал бы «всё хорошо» ровно тогда, когда
# всё плохо. Каждый шаг выше выходит с exit 1 и сюда не доходит.
heartbeat "CRAWL"

say "=== прогон $MODE закончен за $(( $(date +%s) - started )) с ==="
