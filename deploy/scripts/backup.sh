#!/usr/bin/env bash
#
# Ежедневный дамп Postgres. Хранение 30 дней.
#
# pg_dump в custom-формате (-Fc), а не plain SQL: он сжат, и из него можно
# восстановить одну таблицу, не разворачивая всю базу. Разница видна ровно
# один раз — когда надо срочно вернуть одну испорченную таблицу.
#
# Секции price_observations попадают в дамп как обычные таблицы: pg_dump
# понимает партиционирование и восстанавливает структуру целиком.
# -e: любая необработанная ошибка останавливает скрипт. -E: ловушка ERR из
# lib.sh работает и внутри функций. Без -e упавший шаг шёл дальше, и прогон
# заканчивался успехом на половине сделанного.
set -Eeuo pipefail

ROOT=${ROOT:-/srv/qiymet}
BACKUP_DIR=${BACKUP_DIR:-/backups}
LOG_DIR=${LOG_DIR:-/var/log/qiymet}
LOG="$LOG_DIR/backup.log"
KEEP_DAYS=${BACKUP_KEEP_DAYS:-30}

mkdir -p "$BACKUP_DIR" "$LOG_DIR"

SCRIPT_NAME=$(basename "$0")

# shellcheck source=lib.sh
. "$(dirname "$0")/lib.sh"

exec >> >(rotating_tee "$LOG") 2>&1

stamp=$(date '+%Y-%m-%d')
target="$BACKUP_DIR/qiymet-${stamp}.dump"
tmp="${target}.part"

say "=== бэкап $stamp начат ==="

# Пишем во временный файл и переименовываем только после успеха. Иначе
# оборванный дамп ляжет рядом с настоящими и будет неотличим от них до того
# самого дня, когда понадобится.
if ! pg_dump --format=custom --compress=6 --file="$tmp"; then
    rm -f "$tmp"
    alert "Бэкап Postgres упал ($stamp). Сегодняшней копии нет."
    exit 1
fi
mv -f "$tmp" "$target"

size=$(du -h "$target" | cut -f1)
say "бэкап готов: $target ($size)"

# Дамп нулевого размера технически успешен: pg_dump вернёт ноль и на пустой
# базе. Проверяем содержимое, а не код возврата.
# stderr НЕ выбрасывается: «дамп повреждён» пишется именно туда, и
# заглушив его, мы бы получили tables=0 и сообщение «снят с пустой базы» —
# правдоподобное, но неверное.
if ! listing=$(pg_restore --list "$target" 2>&1); then
    alert "Бэкап $stamp снят, но не читается: pg_restore --list падает.
$(printf '%s' "$listing" | tail -3)"
    exit 1
fi
# `|| true` здесь единственное на все скрипты и оправдано: grep -c возвращает
# единицу, когда совпадений НОЛЬ, а ноль таблиц с данными — это не сбой grep,
# а результат, который проверяется следующей строкой.
tables=$(printf '%s' "$listing" | grep -c 'TABLE DATA' || true)
if [ "$tables" -lt 5 ]; then
    alert "Бэкап $stamp содержит только $tables таблиц с данными. Похоже, дамп снят с пустой базы."
    exit 1
fi
say "в дампе таблиц с данными: $tables"

# --- уборка -------------------------------------------------------------------
# Удаляем строго старше KEEP_DAYS и только свои файлы: -name с маской, а не
# всё подряд в каталоге. Каталог общий, и «rm всё старше 30 дней» однажды
# унесёт что-нибудь чужое.
removed=$(find "$BACKUP_DIR" -maxdepth 1 -name 'qiymet-*.dump' \
               -mtime "+$KEEP_DAYS" -print -delete | wc -l)
# if, а не `[ ... ] && say`: при set -e ложное условие сделало бы последний
# код возврата единицей и уронило бы скрипт в день, когда удалять нечего.
if [ "$removed" -gt 0 ]; then
    say "удалено старых копий: $removed"
fi

kept=$(find "$BACKUP_DIR" -maxdepth 1 -name 'qiymet-*.dump' | wc -l)
say "копий в хранилище: $kept"

# Тридцать дней хранения — это тридцать файлов. Если их заметно меньше,
# значит какие-то дни бэкап не снимался, и узнать об этом лучше сейчас.
if [ "$kept" -lt "$((KEEP_DAYS - 2))" ] && [ "$kept" -lt 28 ]; then
    say "копий меньше срока хранения — база молодая либо были пропуски"
fi

free=$(df -h "$BACKUP_DIR" | awk 'NR==2 {print $4}')
say "свободно на диске: $free"

# Место кончается тихо, а кончившееся место роняет Postgres целиком —
# и бэкапы вместе с ним.
free_pct=$(df "$BACKUP_DIR" | awk 'NR==2 {print 100 - $5 + 0}' | tr -d '%')
if [ "${free_pct:-100}" -lt 10 ]; then
    alert "На диске с бэкапами осталось меньше 10% места (свободно $free). Postgres упадёт раньше, чем закончатся копии."
fi

say "=== бэкап $stamp закончен ==="
