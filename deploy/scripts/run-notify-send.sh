#!/usr/bin/env bash
#
# Разбор очереди уведомлений. Каждые 15 минут.
#
# Отдельно от сбора, потому что очередь копится не только сбором: тихие часы
# 23:00-08:00 по Баку откладывают отправку, и в восемь утра накопленное надо
# разослать, не дожидаясь ближайшего прогона.
#
# Здесь именно `send`, а не `run`: разбирать дельты между прогонами нечего,
# новых наблюдений в базе не появилось.
# -e: любая необработанная ошибка останавливает скрипт. -E: ловушка ERR из
# lib.sh работает и внутри функций. Без -e упавший шаг шёл дальше, и прогон
# заканчивался успехом на половине сделанного.
set -Eeuo pipefail

# Путь задаётся снаружи, чтобы скрипт можно было прогнать не только
# в контейнере. По умолчанию — тот, что в образе.
: "${ROOT:=/srv/qiymet}"
: "${LOG_DIR:=$ROOT/logs}"
LOG="$LOG_DIR/notify.log"
mkdir -p "$LOG_DIR"

SCRIPT_NAME=$(basename "$0")

# shellcheck source=lib.sh
. "$ROOT/deploy/scripts/lib.sh"

exec >> >(rotating_tee "$LOG") 2>&1

cd "$ROOT" || exit 1
if ! timeout 10m python3 -m notify send; then
    alert "Отправка уведомлений упала. Очередь осталась на месте, следующий заход через 15 минут."
fi
